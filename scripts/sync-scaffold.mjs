// Turns project/ into shared/scaffold.ts so both the browser and the serverless function
// start from the same files without touching disk at runtime.
import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
const root = path.resolve(import.meta.dirname, "../project");
const files = {};
async function walk(dir) {
  for (const e of await readdir(dir, { withFileTypes: true })) {
    if (e.name === "node_modules" || e.name.startsWith(".")) continue;
    const p = path.join(dir, e.name);
    if (e.isDirectory()) await walk(p);
    else files[path.relative(root, p).split(path.sep).join("/")] = await readFile(p, "utf8");
  }
}
await walk(root);
const out = `// Generated by scripts/sync-scaffold.mjs from project/. Do not edit by hand.\nexport const SCAFFOLD: Record<string, string> = ${JSON.stringify(files, null, 2)};\n`;
await writeFile(path.resolve(import.meta.dirname, "../shared/scaffold.ts"), out);
console.log(`scaffold: ${Object.keys(files).length} files`);
