// Bundles the HyperFrames skill (from ~/.claude/skills/hyperframes) into shared/skill-bundle.ts
// so the hosted deployment has the same instructions. Keeps the committed copy when the
// source directory is missing (e.g. on Vercel's build machine).
import { readFile, writeFile, access } from "node:fs/promises";
import path from "node:path";
import os from "node:os";
const dir = process.env.HF_SKILL_DIR ?? path.join(os.homedir(), ".claude/skills/hyperframes");
const out = path.resolve(import.meta.dirname, "../shared/skill-bundle.ts");
try { await access(path.join(dir, "SKILL.md")); } catch { console.log("skill source missing; keeping shared/skill-bundle.ts"); process.exit(0); }
const [skill, format, motion] = await Promise.all(["SKILL.md", "references/format.md", "references/motion.md"].map((f) => readFile(path.join(dir, f), "utf8")));
await writeFile(out, `// Generated by scripts/sync-skill.mjs from ${dir.replace(os.homedir(), "~")}. Do not edit by hand.\nexport const SKILL_BUNDLE = ${JSON.stringify({ skill, format, motion }, null, 2)};\n`);
console.log(`skill bundle: ${(skill.length + format.length + motion.length) / 1000 | 0}k chars`);
